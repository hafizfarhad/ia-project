"""Export the latest evaluation into LaTeX for the report (report/generated/*.tex).

Reads the evaluator's latest snapshot and run statistics as the read-only aml_eval role, and the
model card from the API container, so every number in the report comes from the running system.

    .venv/bin/python scripts/export_results.py
"""
from __future__ import annotations

import json
import subprocess
from pathlib import Path

import psycopg
from psycopg.rows import dict_row

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "report" / "generated"
SCN = {"S1": "Structuring", "S2": "Fan-in/out mule", "S3": "Pass-through", "S4": "Layering chain",
       "S5": "Round-trip", "S6": "Shared device", "ML": "Model risk"}
TYP = {"S1_STRUCTURING": "Structuring", "S2_FAN_IN_OUT": "Fan-in/out mule", "S3_PASS_THROUGH": "Pass-through",
       "S4_LAYERING": "Layering chain", "S5_ROUND_TRIP": "Round-trip"}
LOOK = {"COMMITTEE": "Committee organisers", "SALARY": "Salary employers", "FAMILY": "Family chain members",
        "SHARED_PHONE": "Shared-phone wallets"}


def env() -> dict:
    out = {}
    for line in (ROOT / ".env").read_text().splitlines():
        if "=" in line and not line.startswith("#"):
            k, v = line.split("=", 1)
            out[k] = v
    return out


def pct(x) -> str:
    return "---" if x is None else f"{100 * x:.0f}\\%"


def num(x) -> str:
    return "---" if x is None else f"{x:.2f}"


def main() -> None:
    e = env()
    with psycopg.connect(host="localhost", dbname="walletwatch", user="aml_eval",
                         password=e["EVAL_DB_PASSWORD"], row_factory=dict_row) as c:
        snap = c.execute("SELECT payload FROM eval_snapshots ORDER BY snapshot_id DESC LIMIT 1").fetchone()["payload"]
        run = c.execute("SELECT count(*) AS n, min(ts) AS t0, max(ts) AS t1 FROM transactions "
                        "WHERE txn_id NOT LIKE 'ZZ%%'").fetchone()
        illicit = c.execute("SELECT count(*) AS n FROM ground_truth g JOIN transactions t USING (txn_id) "
                            "WHERE g.label='illicit'").fetchone()["n"]
        alerts = c.execute("SELECT count(*) AS n FROM alerts").fetchone()["n"]
    meta = json.loads(subprocess.run(["docker", "compose", "exec", "-T", "api", "cat", "/app/models/meta.json"],
                                     cwd=ROOT, capture_output=True, text=True, check=True).stdout)
    tests = subprocess.run([str(ROOT / ".venv/bin/pytest"), "--collect-only", "-q"], cwd=ROOT,
                           capture_output=True, text=True).stdout.strip().splitlines()[-1].split()[0]

    o, t = snap["overall"], meta["test"]
    days = (run["t1"] - run["t0"]).days + 1
    macros = {
        "ResTxns": f"{run['n']:,}", "ResDays": str(days), "ResAlerts": f"{alerts:,}",
        "ResIllicitPct": f"{100 * illicit / run['n']:.2f}\\%",
        "ResAccountsAlerted": str(o["accounts_alerted"]), "ResTP": str(o["true_positive"]),
        "ResIllicitActive": str(o["illicit_accounts_active"]),
        "ResPrecisionPct": pct(o["precision"]), "ResRecallPct": pct(o["recall"]),
        "ResMLPRAUC": f"{t['pr_auc']:.2f}", "ResMLROC": f"{t['roc_auc']:.3f}",
        "ResMLPrec": f"{t['precision_at_thr']:.2f}", "ResMLRec": f"{t['recall_at_thr']:.2f}",
        "ResMLTestTxns": f"{t['txns']:,}", "ResMLTestIllicit": str(t["illicit"]),
        "ResMLCommittee": pct(t["by_typology"].get("COMMITTEE", {}).get("flag_rate")),
        "ResTests": tests,
    }
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "results.tex").write_text("% Generated by scripts/export_results.py — do not edit.\n" +
                                     "".join(f"\\newcommand{{\\{k}}}{{{v}}}\n" for k, v in macros.items()))

    rows_s = "\n".join(
        f"{k} & {SCN[k]} & {v['accounts_alerted']} & {v['true_positive']} & {v['lookalike_fp']} & "
        f"{v['other_fp']} & {pct(v['precision'])} \\\\" for k, v in snap["by_scenario"].items())
    rows_t = "\n".join(
        f"{TYP.get(k, k)} & {v['active']} & {pct(v['recall_rules'])} & {pct(v['recall_rules_plus_ml'])} \\\\"
        for k, v in sorted(snap["by_typology"].items()))
    ttd: dict[str, list[int]] = {}
    for r in snap["time_to_detect"].values():
        if r["minutes_to_detect"] is not None:
            ttd.setdefault(r["typology"], []).append(r["minutes_to_detect"])
    rows_d = "\n".join(
        f"{TYP.get(k, k)} & {len(v)} & {min(v) / 60:.1f} & {max(v) / 60:.1f} \\\\" for k, v in sorted(ttd.items()))
    rows_l = "\n".join(
        f"{LOOK.get(k, k)} & {v['accounts']} & {v['alerted']} \\\\" for k, v in sorted(snap["lookalikes"].items()))

    tables = rf"""% Generated by scripts/export_results.py — do not edit.
\begin{{table}}[!t]
\caption{{Live run: accounts alerted per scenario}}\label{{tab:live}}
\centering\tbl
\begin{{tabularx}}{{\columnwidth}}{{@{{}}llrrrrr@{{}}}}
\toprule
ID & Scenario & Alerted & TP & Look-alike & Other & Prec. \\ \midrule
{rows_s}
\midrule
\multicolumn{{2}}{{@{{}}l}}{{All scenarios (distinct accounts)}} & {o['accounts_alerted']} & {o['true_positive']} & \multicolumn{{2}}{{c}}{{}} & {pct(o['precision'])} \\
\bottomrule
\end{{tabularx}}
\end{{table}}

\begin{{table}}[!t]
\caption{{Live run: recall by typology, time to detect, look-alikes}}\label{{tab:typo}}
\centering\tbl
\begin{{tabularx}}{{\columnwidth}}{{@{{}}Xrrr@{{}}}}
\toprule
Typology & Active accounts & Recall (rules) & Recall (+ML) \\ \midrule
{rows_t}
\midrule
\multicolumn{{3}}{{@{{}}l}}{{Overall recall, active illicit accounts ({o['illicit_accounts_active']})}} & {pct(o['recall'])} \\
\bottomrule
\end{{tabularx}}\\[6pt]
\begin{{tabularx}}{{\columnwidth}}{{@{{}}Xrrr@{{}}}}
\toprule
Typology & Rings detected & Fastest (h) & Slowest (h) \\ \midrule
{rows_d}
\bottomrule
\end{{tabularx}}\\[6pt]
\begin{{tabularx}}{{\columnwidth}}{{@{{}}Xrr@{{}}}}
\toprule
Benign look-alike & Accounts & Alerted \\ \midrule
{rows_l}
\bottomrule
\end{{tabularx}}
\end{{table}}
"""
    (OUT / "results_tables.tex").write_text(tables)
    print(json.dumps(macros, indent=1))


if __name__ == "__main__":
    main()
